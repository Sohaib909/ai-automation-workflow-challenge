import Link from "next/link";
import type { ReactNode } from "react";
import type { QCFlag } from "@/lib/qc";

export function Card({ title, actions, children, className = "" }: { title?: ReactNode; actions?: ReactNode; children: ReactNode; className?: string }) {
  return (
    <section className={`rounded-lg border border-line bg-surface p-4 ${className}`}>
      {(title || actions) && (
        <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
          {title && <h2 className="text-[15px] font-semibold">{title}</h2>}
          {actions}
        </div>
      )}
      {children}
    </section>
  );
}

export function PageHeader({ title, subtitle, children }: { title: string; subtitle?: ReactNode; children?: ReactNode }) {
  return (
    <div className="mb-5 flex flex-wrap items-end justify-between gap-3">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight">{title}</h1>
        {subtitle && <p className="mt-1 max-w-3xl text-sm text-muted">{subtitle}</p>}
      </div>
      {children}
    </div>
  );
}

const TONES = {
  neutral: "bg-surface-2 text-muted",
  good: "bg-good-soft text-good",
  warn: "bg-warn-soft text-warn",
  bad: "bg-bad-soft text-bad",
  info: "bg-info-soft text-info",
  accent: "bg-accent-soft text-accent",
} as const;
export type Tone = keyof typeof TONES;

export function Badge({ tone = "neutral", children, title }: { tone?: Tone; children: ReactNode; title?: string }) {
  return (
    <span title={title} className={`inline-flex items-center gap-1 whitespace-nowrap rounded-full px-2 py-0.5 text-xs font-medium ${TONES[tone]}`}>
      {children}
    </span>
  );
}

const STATUS: Record<string, [Tone, string]> = {
  draft: ["neutral", "Draft"],
  pending_review: ["info", "● Pending review"],
  approved: ["good", "✓ Approved"],
  ai_selected: ["accent", "★ AI pick · needs your OK"],
  rejected: ["bad", "✕ Rejected"],
  changes_requested: ["warn", "↺ Changes requested"],
  archived: ["neutral", "Archived"],
  open: ["info", "● Open"],
  dismissed: ["neutral", "Dismissed"],
};
export function StatusBadge({ status }: { status: string }) {
  const [tone, label] = STATUS[status] ?? ["neutral", status];
  return <Badge tone={tone}>{label}</Badge>;
}

export function ProviderBadge({ provider, model }: { provider: string; model: string }) {
  if (provider === "mock") return <Badge tone="warn" title="Template output from the mock provider — not AI-generated">Mock provider</Badge>;
  if (provider === "human") return <Badge tone="neutral">Edited by human</Badge>;
  return <Badge tone="accent" title={`Generated by ${provider}`}>AI · {provider}/{model}</Badge>;
}

const FLAG: Record<QCFlag["level"], [Tone, string]> = { error: ["bad", "✕"], warning: ["warn", "!"], info: ["info", "i"] };
export function QCList({ flags }: { flags: QCFlag[] }) {
  if (!flags.length) return <p className="text-xs text-good">✓ QC passed — no flags</p>;
  return (
    <ul className="space-y-1">
      {flags.map((f, i) => (
        <li key={i} className="flex items-start gap-2 text-xs">
          <Badge tone={FLAG[f.level][0]}>
            {FLAG[f.level][1]} {f.level}
          </Badge>
          <span className="pt-0.5 text-muted">
            {f.field && <strong className="text-ink">{f.field.replace("_", " ")}: </strong>}
            {f.message}
          </span>
        </li>
      ))}
    </ul>
  );
}

export function Empty({ children }: { children: ReactNode }) {
  return <div className="rounded-md border border-dashed border-line p-6 text-center text-sm text-muted">{children}</div>;
}

export function LinkButton({ href, children, variant = "secondary" }: { href: string; children: ReactNode; variant?: "primary" | "secondary" }) {
  return (
    <Link href={href} className={btn(variant)}>
      {children}
    </Link>
  );
}

export function btn(variant: "primary" | "secondary" | "danger" | "ghost" = "secondary") {
  const base = "inline-flex items-center justify-center gap-1.5 rounded-md px-3 py-1.5 text-sm font-medium transition-colors disabled:opacity-50 disabled:cursor-not-allowed";
  return {
    primary: `${base} bg-accent text-white hover:opacity-90`,
    secondary: `${base} border border-line bg-surface hover:bg-surface-2`,
    danger: `${base} border border-line bg-surface text-bad hover:bg-bad-soft`,
    ghost: `${base} text-muted hover:bg-surface-2`,
  }[variant];
}

export function fmtDate(iso: string) {
  return new Date(iso).toLocaleString("en-GB", { day: "2-digit", month: "short", hour: "2-digit", minute: "2-digit" });
}
